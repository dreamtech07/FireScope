export function generateSyntheticObservations(): FireObservation[] {
  const currentNow = Date.now();
  return SEED_DATA.map((seed) => {
    const timestampMs = currentNow - seed.hoursAgo * hourMs;
    const acqDateObj = new Date(timestampMs);
    const acqTimestampUtc = acqDateObj.toISOString();
    const acqDate = acqTimestampUtc.slice(0, 10);
    const acqTime = acqTimestampUtc.slice(11, 16).replace(':', '');

    const draft: Omit<FireObservation, 'score'> = {
      id: seed.id,
      sourceProvider: 'SYNTHETIC_DEMO',
      isSynthetic: true,
      platform: seed.platform,
      sensorFamily: seed.sensorFamily,
      satellite: seed.platform.replace(/_/g, ' '),
      latitude: seed.latitude,
      longitude: seed.longitude,
      acqTimestampUtc,
      acqDate,
      acqTime,
      dayNight: seed.dayNight,
      brightness: seed.brightness,
      brightT31: seed.brightT31,
      frp: seed.frp,
      confidence: seed.confidence,
      confidenceCategory: seed.confidenceCategory,
      version: '2.0-NRT',
      ingestionTimestampUtc: new Date(currentNow - 10 * 60 * 1000).toISOString(),
      qualityWarnings: seed.qualityWarnings || [],
      repeatObservationCount: seed.hoursAgo < 12 ? 3 : 1,
      region: seed.region,
      country: seed.country,
      landCoverType: seed.landCoverType,
    };

    const score = computePriorityScore(draft, DEFAULT_WEIGHTS, new Date(currentNow));

    return {
      ...draft,
      score,
    };
  });
}
